"""실제 사진이 드러낸 실패 유형(시나리오)별 회귀 방지선.

train/benchmark.py 의 성능 보드를 테스트로 고정한 것이다. 시나리오마다 "지금 이 정도는 나온다"는
실측값에 여유를 둔 값이 기준이다. 어떤 수정이 특정 유형을 망가뜨리면 여기서 걸린다.

시나리오가 왜 있는지(각각 실제 사진 한 장에서 왔다):
  음영도형  — 적분 반원 사진: 회색으로 면을 채운 도형이 조명 정규화에서 흰색으로 날아갔다
  저해상도  — 335x597 사진들: 픽셀 단위 기준값이 전부 어긋나 색펜 제거 34%, 컬러 인쇄 손실 52%
  흑백저장  — 초등 문제집 사진: 색이 없어 빨간펜 고리가 남고, 그 고리가 진하기 기준을 망가뜨렸다
  화면캡처  — 고3 모의고사 캡처: 검은 여백이 화면의 13% 를 차지해 본문이 통째로 지워졌다
"""

from __future__ import annotations

import pytest

from train.benchmark import run_benchmark

SEEDS_PER_SCENARIO = 4

# 실측(2026-09-20, 시나리오당 6장 평균)에 여유를 둔 회귀 방지선.
#   연필제거 ↑ : 기본 47 / 음영 43 / 저해상도 39 / 흑백 25 / 캡처 49
#   인쇄손실 ↓ : 5.2 / 5.1 / 2.4 / 7.8 / 10.3
#   도형손실 ↓ : 0.7 / 0.1 / 0.0 / 0.3 / 2.1
#   컬러인쇄손실 ↓ : 7.8 / 9.4 / 3.7 / — / 10.1
#   손그림강조 ↓ : 4.6 / 3.0 / 7.2 / 4.9 / 2.8
LIMITS = {
    "기본":     {"연필제거": 0.38, "인쇄손실": 0.09, "도형손실": 0.04, "컬러인쇄손실": 0.18, "손그림강조": 0.10},
    "음영도형": {"연필제거": 0.34, "인쇄손실": 0.09, "도형손실": 0.04, "컬러인쇄손실": 0.20, "손그림강조": 0.10},
    "저해상도": {"연필제거": 0.30, "인쇄손실": 0.07, "도형손실": 0.05, "컬러인쇄손실": 0.15, "손그림강조": 0.14},
    "흑백저장": {"연필제거": 0.18, "인쇄손실": 0.13, "도형손실": 0.05, "컬러인쇄손실": None, "손그림강조": 0.12},
    "화면캡처": {"연필제거": 0.38, "인쇄손실": 0.16, "도형손실": 0.07, "컬러인쇄손실": 0.20, "손그림강조": 0.10},
}


@pytest.fixture(scope="module")
def board() -> dict[str, dict[str, float]]:
    """모든 시나리오를 한 번만 재서 테스트들이 나눠 쓴다."""
    return run_benchmark(SEEDS_PER_SCENARIO, "보통", list(LIMITS))


@pytest.mark.parametrize("scenario", list(LIMITS))
def test_scenario_does_not_regress(board: dict[str, dict[str, float]], scenario: str) -> None:
    """시나리오별로 필기는 충분히 지우고 인쇄·도형·컬러 인쇄는 지키며 손그림을 강조하지 않는다."""
    assert scenario in board, f"{scenario} 시나리오가 한 장도 측정되지 않았다(크기 정렬 실패?)."
    values = board[scenario]
    limits = LIMITS[scenario]

    print(f"\n[{scenario}] 연필제거 {values['연필제거']*100:.0f}% / 인쇄손실 {values['인쇄손실']*100:.1f}% / "
          f"도형손실 {values['도형손실']*100:.1f}% / 컬러인쇄손실 {values['컬러인쇄손실']*100:.1f}% / "
          f"손그림강조 {values['손그림강조']*100:.1f}%")

    assert values["연필제거"] >= limits["연필제거"], "연필·볼펜 필기를 충분히 지우지 못한다."
    assert values["인쇄손실"] <= limits["인쇄손실"], "인쇄 글자가 지워지고 있다."
    assert values["도형손실"] <= limits["도형손실"], "그래프·도형이 지워지고 있다. 가장 치명적인 실패다."
    if limits["컬러인쇄손실"] is not None:
        assert values["컬러인쇄손실"] <= limits["컬러인쇄손실"], "컬러 인쇄(제목 띠·아이콘·번호)가 지워지고 있다."
    assert values["손그림강조"] <= limits["손그림강조"], "학생이 그린 그림이 인쇄 도형으로 오인돼 강조되고 있다."
